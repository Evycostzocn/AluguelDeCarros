CREATE TABLE public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(100) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuarios_usuario UNIQUE (usuario),
    CONSTRAINT ck_usuarios_usuario CHECK (btrim(usuario) <> ''),
    CONSTRAINT ck_usuarios_senha_hash CHECK (btrim(senha_hash) <> '')
);

CREATE TABLE public.clientes (
    id BIGINT PRIMARY KEY,
    rg VARCHAR(30) NOT NULL CHECK (btrim(rg) <> ''),
    cpf VARCHAR(11) NOT NULL,
    nome VARCHAR(200) NOT NULL CHECK (btrim(nome) <> ''),
    endereco VARCHAR(500) NOT NULL CHECK (btrim(endereco) <> ''),
    profissao VARCHAR(150) NOT NULL CHECK (btrim(profissao) <> ''),
    CONSTRAINT fk_clientes_usuarios FOREIGN KEY (id) REFERENCES public.usuarios (id),
    CONSTRAINT uk_clientes_cpf UNIQUE (cpf),
    CONSTRAINT ck_clientes_cpf_formato CHECK (cpf ~ '^[0-9]{11}$')
);

CREATE TABLE public.vinculos_renda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    entidade_empregadora VARCHAR(200) NOT NULL CHECK (btrim(entidade_empregadora) <> ''),
    rendimento NUMERIC(15, 2) NOT NULL,
    CONSTRAINT fk_vinculos_renda_clientes FOREIGN KEY (cliente_id) REFERENCES public.clientes (id),
    CONSTRAINT ck_vinculos_renda_rendimento CHECK (rendimento > 0 AND rendimento <> 'NaN'::numeric)
);

CREATE INDEX ix_vinculos_renda_cliente_id ON public.vinculos_renda (cliente_id);
