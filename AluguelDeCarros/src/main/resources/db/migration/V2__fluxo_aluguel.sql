CREATE TABLE public.agentes (
    id BIGINT PRIMARY KEY REFERENCES public.usuarios(id),
    nome VARCHAR(200) NOT NULL CHECK (btrim(nome) <> ''),
    cnpj VARCHAR(14) NOT NULL CHECK (cnpj ~ '^[0-9]{14}$'),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('EMPRESA', 'BANCO'))
);
CREATE TABLE public.automoveis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(50) NOT NULL UNIQUE,
    ano INTEGER NOT NULL CHECK (ano BETWEEN 1886 AND 9999),
    marca VARCHAR(100) NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    placa VARCHAR(10) NOT NULL UNIQUE,
    proprietario_cliente_id BIGINT REFERENCES public.clientes(id),
    proprietario_agente_id BIGINT REFERENCES public.agentes(id),
    CONSTRAINT ck_automovel_proprietario CHECK (
        (proprietario_cliente_id IS NOT NULL) <> (proprietario_agente_id IS NOT NULL)
    )
);
CREATE TABLE public.pedidos_aluguel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id),
    automovel_id BIGINT NOT NULL REFERENCES public.automoveis(id),
    data_criacao TIMESTAMP NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('EM_ANALISE','APROVADO','REPROVADO','CANCELADO','CONTRATADO')),
    CONSTRAINT ck_pedido_periodo CHECK (data_fim > data_inicio)
);
CREATE INDEX ix_pedidos_cliente ON public.pedidos_aluguel(cliente_id);
CREATE TABLE public.avaliacoes_financeiras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES public.pedidos_aluguel(id),
    agente_id BIGINT NOT NULL REFERENCES public.agentes(id),
    data_avaliacao TIMESTAMP NOT NULL,
    parecer VARCHAR(2000) NOT NULL CHECK (btrim(parecer) <> ''),
    aprovada BOOLEAN NOT NULL
);
CREATE TABLE public.contratos_aluguel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL UNIQUE REFERENCES public.pedidos_aluguel(id),
    agente_id BIGINT NOT NULL REFERENCES public.agentes(id),
    data_celebracao DATE NOT NULL,
    valor NUMERIC(15,2) NOT NULL CHECK (valor > 0 AND valor <> 'NaN'::numeric)
);
CREATE TABLE public.contratos_credito (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_aluguel_id BIGINT NOT NULL UNIQUE REFERENCES public.contratos_aluguel(id),
    banco_id BIGINT NOT NULL REFERENCES public.agentes(id),
    valor NUMERIC(15,2) NOT NULL CHECK (valor > 0 AND valor <> 'NaN'::numeric),
    quantidade_parcelas INTEGER NOT NULL CHECK (quantidade_parcelas > 0)
);
